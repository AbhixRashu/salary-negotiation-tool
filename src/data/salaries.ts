export function getSalaryEstimate(
  roleName: string,
  metroId: string,
  experienceId: string
) {
  const match = ROLES.find(r => r.role.toLowerCase() === roleName.toLowerCase());
  const metro = METRO_AREAS.find(m => m.id === metroId) || { multiplier: 1.0 };
  const exp = EXPERIENCE_LEVELS.find(e => e.id === experienceId) || { multiplier: 1.0 };
  const mult = metro.multiplier * exp.multiplier;

  if (match) {
    return {
      median: Math.round(match.median * mult),
      low: Math.round(match.low * mult),
      high: Math.round(match.high * mult),
      isFallback: false
    };
  }

  const baseMedian = 85000;
  return {
    median: Math.round(baseMedian * mult),
    low: Math.round(baseMedian * 0.78 * mult),
    high: Math.round(baseMedian * 1.25 * mult),
    isFallback: true
  };
}
